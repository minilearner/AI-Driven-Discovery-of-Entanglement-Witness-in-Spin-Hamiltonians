"""Frozen three-seed Dv1-only Joint-K16 inference.

Input is the 122-channel, site-resolved LU-invariant tensor produced by
``structured_inv123_raw_t4_local_tokens``. The last five channels are
deterministic geometry masks; only the 16 frozen physical channels are selected.
"""

from __future__ import annotations

import hashlib
import json
from pathlib import Path

import numpy as np
import torch

from entanglement_data.ml.invariant_transformer import (
    InvariantTokenTransformer,
    InvariantTransformerConfig,
    NormalizedInvariantTransformer,
    structured_inv123_raw_t4_local_tokens,
)
from entanglement_data.observables.feature_spec import FeatureSpec
from entanglement_data.observables.lu_invariants import (
    connected_third_cumulant,
    connected_two_body,
    decode_correlators,
)

SEEDS = (20260829, 20260830, 20260831)


def tokens_from_pauli_features(features: np.ndarray, *, N: int) -> np.ndarray:
    """Convert canonical raw Pauli features ``[B,F]`` to full ``[B,N,122]`` tokens.

    Pair supports use forward distances 1..4 and the feature boundary does not
    wrap. The 5 geometry masks are generated by the original token builder.
    """
    spec = FeatureSpec(N)
    decoded = decode_correlators(features, spec)
    if decoded.single_input:
        raise ValueError("provide a batch of features with shape [B,F]")
    batch = len(decoded.one)
    raw_two = np.zeros((batch, N, 4, 3, 3), dtype=np.float64)
    connected_two = np.zeros_like(raw_two)
    connected_flat = connected_two_body(decoded)
    for index, (left, right) in enumerate(zip(decoded.pair_left, decoded.pair_right)):
        distance = int(right - left)
        if distance > 4:
            continue
        raw_two[:, left, distance - 1] = decoded.two[:, index]
        connected_two[:, left, distance - 1] = connected_flat[:, index]
    raw_three = np.zeros((batch, N, 3, 3, 3), dtype=np.float64)
    connected_three = np.zeros_like(raw_three)
    raw_three[:, :N - 2] = decoded.three
    connected_three[:, :N - 2] = connected_third_cumulant(decoded)
    raw_four = np.zeros((batch, N, 3, 3, 3, 3), dtype=np.float64)
    raw_four[:, :N - 3] = decoded.four
    return structured_inv123_raw_t4_local_tokens(
        decoded.one, raw_two, connected_two, raw_three, connected_three,
        raw_four, R_obs=4, output_dtype=np.float32,
    )


def _manifest(root: Path) -> tuple[list[int], str]:
    path = root / "configs" / "joint_K16.json"
    raw = path.read_bytes()
    content = json.loads(raw)
    if content["physical_channel_count"] != 16 or content["mask_channel_count"] != 5:
        raise ValueError("expected 16 frozen physical channels and 5 masks")
    channels = [int(v) for v in content["selected_full_token_channels"]]
    if len(channels) != 21 or channels[-5:] != list(range(117, 122)):
        raise ValueError("frozen channel or mask schema changed")
    return channels, hashlib.sha256(raw).hexdigest()


def load_final_ensemble(root: Path, *, device: str = "cpu") -> tuple[list[torch.nn.Module], list[int]]:
    """Load final weights and validate each checkpoint against the frozen manifest."""
    root = Path(root)
    channels, manifest_hash = _manifest(root)
    models = []
    for seed in SEEDS:
        directory = root / "checkpoints" / "final_joint_k16" / f"seed{seed}"
        saved = json.loads((directory / "model_config.json").read_text(encoding="utf-8"))
        if saved["training_route"] != "Dv1_only" or saved["training_sources"] != ["D_v1"]:
            raise ValueError(f"seed {seed}: training route is not final Dv1-only")
        if saved["selected_full_token_channels"] != channels:
            raise ValueError(f"seed {seed}: selected channels differ")
        if saved["selection_manifest_byte_sha256"] != manifest_hash:
            raise ValueError(f"seed {seed}: selection manifest hash differs")
        config = InvariantTransformerConfig(**saved["model_config"])
        mean = np.load(directory / "input_mean.npy")
        std = np.load(directory / "input_std.npy")
        model = NormalizedInvariantTransformer(InvariantTokenTransformer(config), mean, std)
        checkpoint = torch.load(directory / "best.pt", map_location="cpu", weights_only=True)
        if checkpoint["metadata"]["train_route_hash"] != saved["train_route_hash"]:
            raise ValueError(f"seed {seed}: checkpoint training-route hash differs")
        model.load_state_dict(checkpoint["model_state_dict"], strict=True)
        model.eval().to(device)
        models.append(model)
    return models, channels


def predict_final_ensemble(
    full_tokens: np.ndarray,
    root: Path,
    *,
    device: str = "cpu",
    batch_size: int = 256,
) -> np.ndarray:
    """Return probability-averaged ensemble scores for ``[B,N,122]`` tokens."""
    models, channels = load_final_ensemble(root, device=device)
    full_tokens = np.asarray(full_tokens)
    if full_tokens.ndim != 3 or full_tokens.shape[2] != 122:
        raise ValueError("expected full LU-invariant tokens with shape [B,N,122]")
    if not np.isfinite(full_tokens).all():
        raise ValueError("input contains non-finite values")
    selected = np.ascontiguousarray(full_tokens[:, :, channels], dtype=np.float32)
    outputs = []
    with torch.inference_mode():
        for start in range(0, len(selected), batch_size):
            values = torch.from_numpy(selected[start:start + batch_size]).to(device)
            outputs.append(np.mean([
                torch.sigmoid(model(values)).cpu().numpy() for model in models
            ], axis=0))
    return np.concatenate(outputs) if outputs else np.empty(0, dtype=np.float32)
